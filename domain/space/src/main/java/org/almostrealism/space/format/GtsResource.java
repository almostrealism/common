package org.almostrealism.space.format;

import io.almostrealism.resource.ResourceTranscoder;
import io.almostrealism.resource.UnicodeResource;
import org.almostrealism.algebra.Vector;
import org.almostrealism.space.Mesh;
import org.almostrealism.space.Triangle;

import java.io.IOException;
import java.util.ArrayList;
import java.util.List;

/**
 * A mesh in the GNU Triangulated Surface (GTS) text format.
 *
 * <p>The data is a header line {@code vertices edges triangles}, then one line of
 * {@code x y z} per vertex, one line of two vertex indices per edge, and one line of three
 * edge indices per triangle. Indices start at 1. Lines starting with {@code #} are
 * comments.</p>
 */
public class GtsResource extends UnicodeResource {
	/**
	 * Creates an empty GTS resource, to be loaded.
	 */
	public GtsResource() { }

	/**
	 * Creates a GTS resource holding the given text.
	 *
	 * @param data the GTS text
	 */
	public GtsResource(String data) { super(data); }

	/**
	 * Writes a {@link MeshResource} as GTS, with three edges per triangle.
	 */
	public static class MeshTranscoder implements ResourceTranscoder<MeshResource, GtsResource> {
		@Override
		public GtsResource transcode(MeshResource r) {
			Mesh m = r.getMesh();
			Vector[] v = m.getVectors();
			Triangle[] t = m.getTriangles();

			StringBuilder buf = new StringBuilder();
			buf.append("# GTS output generated by Almost Realism Common Library (almostrealism.org)\n");
			buf.append(v.length).append(" ").append(3 * t.length).append(" ").append(t.length).append("\n");

			for (Vector vertex : v) {
				buf.append(vertex.getX()).append(" ").append(vertex.getY()).append(" ")
						.append(vertex.getZ()).append("\n");
			}

			for (Triangle triangle : t) {
				Vector[] tv = triangle.getVertices();

				for (int i = 0; i < 3; i++) {
					buf.append(m.indexOf(tv[i]) + 1).append(" ")
							.append(m.indexOf(tv[(i + 1) % 3]) + 1).append("\n");
				}
			}

			for (int i = 0; i < t.length; i++) {
				int edge = 3 * i + 1;
				buf.append(edge).append(" ").append(edge + 1).append(" ").append(edge + 2).append("\n");
			}

			return new GtsResource(buf.toString());
		}
	}

	/**
	 * Reads a {@link GtsResource} into a {@link MeshResource}.
	 */
	public static class MeshReader implements ResourceTranscoder<GtsResource, MeshResource> {
		/** The mesh to add the data to, or {@code null} to create a new one. */
		private Mesh initial;

		/**
		 * Sets a mesh that the vertices and triangles read are added to, in place of a new one.
		 *
		 * @param m the mesh, or {@code null} to create a new one
		 */
		public void setInitialMesh(Mesh m) { this.initial = m; }

		@Override
		public MeshResource transcode(GtsResource r) throws IOException {
			Mesh m = initial == null ? new Mesh() : initial;
			TextFormatReader in = new TextFormatReader("GTS", r.getInputStream());

			double[] counts = in.values(in.next(), 3);
			int pointCount = (int) counts[0];
			int edgeCount = (int) counts[1];
			int triangleCount = (int) counts[2];

			for (int i = 0; i < pointCount; i++) {
				double[] d = in.values(in.next(), 3);
				m.addVector(new Vector(d[0], d[1], d[2]));
			}

			int[][] edges = new int[edgeCount][];

			for (int i = 0; i < edgeCount; i++) {
				double[] d = in.values(in.next(), 2);
				edges[i] = new int[] { (int) d[0] - 1, (int) d[1] - 1 };
			}

			for (int i = 0; i < triangleCount; i++) {
				double[] d = in.values(in.next(), 3);
				List<Integer> vertices = new ArrayList<>();

				for (int j = 0; j < 3; j++) {
					for (int vertex : edges[(int) d[j] - 1]) {
						if (!vertices.contains(vertex)) vertices.add(vertex);
					}
				}

				if (vertices.size() != 3) {
					throw in.error("the edges of a triangle join " + vertices.size() + " vertices");
				}

				m.addTriangle(vertices.get(2), vertices.get(1), vertices.get(0));
			}

			return new MeshResource(m);
		}
	}
}
