package io.flowtree.api;

import fi.iki.elonen.NanoHTTPD;
import fi.iki.elonen.NanoHTTPD.Method;
import fi.iki.elonen.NanoHTTPD.Response;
import io.flowtree.JsonFieldExtractor;
import org.almostrealism.io.ConsoleFeatures;

/**
 * The controller's kill switch for automated job submissions, and the
 * {@code /api/config/accept-automated-jobs} endpoint that reads and sets it.
 *
 * <p>Jobs that self-identify as automated (CI auto-resolve retries,
 * completion-listener wake-ups) are accepted only while the switch is on.
 * It starts on, so a freshly started or redeployed controller accepts
 * automated jobs without a separate {@code controller_update_config} call.
 * Turning it off rejects every {@code automated: true} submission, including
 * the wake-ups generated by the completion-listener fan-out. The
 * completion-listener feature remains ship-inert regardless: configuring
 * listeners stays opt-in per workstream, and a workstream with no
 * {@code completionListeners} spawns no wake-ups whatever this switch says.</p>
 *
 * @author Michael Murray
 * @see FlowTreeApiEndpoint#setAcceptAutomatedJobs(boolean)
 */
public final class AutomatedJobsSwitch implements ConsoleFeatures {

    /** The path of the endpoint that reads and sets the switch. */
    public static final String PATH = "/api/config/accept-automated-jobs";

    /** Whether automated submissions are accepted. */
    private volatile boolean accepting = true;

    /**
     * Returns whether automated job submissions are currently accepted.
     *
     * @return {@code true} if automated jobs are accepted
     */
    public boolean isAccepting() {
        return accepting;
    }

    /**
     * Sets whether automated job submissions are accepted.
     *
     * @param accept {@code true} to accept automated jobs, {@code false} to reject them
     */
    public void setAccepting(boolean accept) {
        this.accepting = accept;
        log("Automated job acceptance " + (accept ? "enabled" : "disabled"));
    }

    /**
     * Answers {@code GET} with the current value, and applies a {@code POST}
     * body's {@code accept} field before answering with the new value.
     *
     * @param method the request method
     * @param body   the request body for a {@code POST}, or {@code null}
     * @return the JSON response, or {@code null} for any other method so the
     *         caller can fall through to its remaining routes
     */
    public Response handle(Method method, String body) {
        if (Method.GET.equals(method)) {
            log("Config query: acceptAutomatedJobs=" + accepting);
            return json("{\"acceptAutomatedJobs\":" + accepting + "}");
        }
        if (!Method.POST.equals(method)) return null;
        if (body != null && body.contains("\"accept\"")) {
            boolean accept = JsonFieldExtractor.extractBoolean(body, "accept");
            log("Config update request: accept-automated-jobs=" + accept + " (was " + accepting + ")");
            setAccepting(accept);
        } else {
            log("Config update request for accept-automated-jobs missing 'accept' field in body");
        }
        return json("{\"ok\":true,\"acceptAutomatedJobs\":" + accepting + "}");
    }

    /**
     * Wraps a JSON body in a {@code 200} response.
     *
     * @param body the JSON body
     * @return the response
     */
    private static Response json(String body) {
        return NanoHTTPD.newFixedLengthResponse(Response.Status.OK, "application/json", body);
    }
}
